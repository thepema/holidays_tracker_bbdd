-- Migración para bases de datos ya inicializadas con el esquema anterior.
-- Ejecutar una sola vez. No asigna oficinas a usuarios automáticamente porque
-- el esquema actual no contiene la ciudad/oficina de cada persona.
BEGIN;

CREATE TABLE IF NOT EXISTS oficinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT oficinas_nombre_no_vacio CHECK (length(trim(nombre)) > 0),
    CONSTRAINT oficinas_nombre_unico UNIQUE (nombre)
);

ALTER TABLE usuarios
    ADD COLUMN IF NOT EXISTS oficina_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'usuarios_oficina_fk'
          AND conrelid = 'usuarios'::regclass
    ) THEN
        ALTER TABLE usuarios
            ADD CONSTRAINT usuarios_oficina_fk
            FOREIGN KEY (oficina_id) REFERENCES oficinas (id) ON DELETE SET NULL;
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS calendarios_oficina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oficina_id BIGINT NOT NULL,
    anio SMALLINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT calendarios_oficina_oficina_fk
        FOREIGN KEY (oficina_id) REFERENCES oficinas (id) ON DELETE CASCADE,
    CONSTRAINT calendarios_oficina_anio_valido CHECK (anio BETWEEN 1900 AND 2200),
    CONSTRAINT calendarios_oficina_anio_unico UNIQUE (oficina_id, anio)
);

CREATE TABLE IF NOT EXISTS dias_festivos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendario_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT dias_festivos_calendario_fk
        FOREIGN KEY (calendario_id) REFERENCES calendarios_oficina (id) ON DELETE CASCADE,
    CONSTRAINT dias_festivos_nombre_no_vacio CHECK (length(trim(nombre)) > 0),
    CONSTRAINT dias_festivos_fecha_unica UNIQUE (calendario_id, fecha)
);

CREATE INDEX IF NOT EXISTS usuarios_oficina_id_idx ON usuarios (oficina_id);
CREATE INDEX IF NOT EXISTS calendarios_oficina_anio_idx ON calendarios_oficina (anio);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'oficinas_actualizar_updated_at'
          AND tgrelid = 'oficinas'::regclass
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER oficinas_actualizar_updated_at
        BEFORE UPDATE ON oficinas
        FOR EACH ROW EXECUTE FUNCTION actualizar_updated_at();
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'calendarios_oficina_actualizar_updated_at'
          AND tgrelid = 'calendarios_oficina'::regclass
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER calendarios_oficina_actualizar_updated_at
        BEFORE UPDATE ON calendarios_oficina
        FOR EACH ROW EXECUTE FUNCTION actualizar_updated_at();
    END IF;
END;
$$;

COMMIT;
